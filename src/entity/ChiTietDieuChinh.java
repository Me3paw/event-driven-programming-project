package entity;

public class ChiTietDieuChinh {
  private String maDieuChinh;
  private long maLo;
  private int soLuongGiam;

  public String getMaDieuChinh() {
    return maDieuChinh;
  }
  public void setMaDieuChinh(String maDieuChinh) {
    this.maDieuChinh = maDieuChinh;
  }
  public long getMaLo() {
    return maLo;
  }
  public void setMaLo(long maLo) {
    this.maLo = maLo;
  }
  public int getSoLuongGiam() {
    return soLuongGiam;
  }
  public void setSoLuongGiam(int soLuongGiam) {
    this.soLuongGiam = soLuongGiam;
  }
}
