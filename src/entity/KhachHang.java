package entity;

public class KhachHang {
  private String maKhachHang;
  private String hoTen;
  private String soDienThoai;
  private long diemHienCo;
  private long diemTichLuy;
  private String trangThai;

  public String getMaKhachHang() {
    return maKhachHang;
  }
  public void setMaKhachHang(String maKhachHang) {
    this.maKhachHang = maKhachHang;
  }
  public String getHoTen() {
    return hoTen;
  }
  public void setHoTen(String hoTen) {
    this.hoTen = hoTen;
  }
  public String getSoDienThoai() {
    return soDienThoai;
  }
  public void setSoDienThoai(String soDienThoai) {
    this.soDienThoai = soDienThoai;
  }
  public long getDiemHienCo() {
    return diemHienCo;
  }
  public void setDiemHienCo(long diemHienCo) {
    this.diemHienCo = diemHienCo;
  }
  public long getDiemTichLuy() {
    return diemTichLuy;
  }
  public void setDiemTichLuy(long diemTichLuy) {
    this.diemTichLuy = diemTichLuy;
  }
  public String getTrangThai() {
    return trangThai;
  }
  public void setTrangThai(String trangThai) {
    this.trangThai = trangThai;
  }
}
